//! Generates the Cypher parser from its pest grammar into a committed Rust
//! file, or, with `--check`, fails when the committed file no longer matches
//! the grammar.
//!
//! Generating ahead of time keeps the parser generator out of every build of
//! the product: the query crate compiles the generated code against pest's
//! runtime alone.

use std::path::{Path, PathBuf};
use std::process::ExitCode;

/// The grammar, relative to the repository root.
const GRAMMAR: &str = "crates/coordinode-query/src/cypher/cypher.pest";
/// The generated parser, relative to the repository root.
const OUTPUT: &str = "crates/coordinode-query/src/cypher/parser/generated.rs";

/// Written above the generated code. The module declaration that includes
/// the file carries `#[rustfmt::skip]`: rustfmt takes minutes on its rules.
const HEADER: &str = "\
// @generated by tools/pest-codegen from cypher.pest. Do not edit by hand:
// change the grammar and run
//     cargo run --manifest-path tools/pest-codegen/Cargo.toml
// CI fails while this file and the grammar disagree.
#![allow(clippy::all, clippy::pedantic, dead_code, unreachable_pub)]

/// The Cypher parser, generated from `cypher.pest`.
pub(crate) struct CypherParser;

";

fn main() -> ExitCode {
    let check = match std::env::args().nth(1).as_deref() {
        None => false,
        Some("--check") => true,
        Some(other) => {
            eprintln!("unknown argument `{other}`; usage: pest-codegen [--check]");
            return ExitCode::from(2);
        }
    };
    let root = repo_root();
    let grammar = match std::fs::read_to_string(root.join(GRAMMAR)) {
        Ok(grammar) => grammar,
        Err(e) => {
            eprintln!("read {GRAMMAR}: {e}");
            return ExitCode::FAILURE;
        }
    };
    let generated = match generate(&grammar) {
        Ok(generated) => generated,
        Err(e) => {
            eprintln!("generate the parser: {e}");
            return ExitCode::FAILURE;
        }
    };
    let output = root.join(OUTPUT);
    if check {
        match std::fs::read_to_string(&output) {
            Ok(committed) if committed == generated => ExitCode::SUCCESS,
            Ok(_) => {
                eprintln!(
                    "{OUTPUT} does not match {GRAMMAR}; regenerate it with \
                     `cargo run --manifest-path tools/pest-codegen/Cargo.toml`"
                );
                ExitCode::FAILURE
            }
            Err(e) => {
                eprintln!("read {OUTPUT}: {e}");
                ExitCode::FAILURE
            }
        }
    } else {
        match std::fs::write(&output, generated) {
            Ok(()) => ExitCode::SUCCESS,
            Err(e) => {
                eprintln!("write {OUTPUT}: {e}");
                ExitCode::FAILURE
            }
        }
    }
}

/// The repository root: this tool lives in `tools/pest-codegen`.
fn repo_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../..")
}

/// The parser `#[derive(pest_derive::Parser)]` would expand to for the
/// grammar, formatted.
fn generate(grammar: &str) -> Result<String, syn::Error> {
    let input = quote::quote! {
        #[grammar_inline = #grammar]
        struct CypherParser;
    };
    let file: syn::File = syn::parse2(pest_generator::derive_parser(input, false))?;
    Ok(format!("{HEADER}{}", prettyplease::unparse(&file)))
}
